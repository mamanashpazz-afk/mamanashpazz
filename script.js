document.addEventListener("DOMContentLoaded", () => {
  const modal=document.getElementById("recipeModal");
  const modalContent=document.getElementById("modalRecipeContent");
  const closeButton=document.getElementById("closeModal");
  const backdrop=document.getElementById("modalBackdrop");
  const searchInput=document.getElementById("searchInput");
  const recipesGrid=document.querySelector(".recipes-grid");

  if(!modal||!modalContent||!closeButton||!backdrop||!searchInput||!recipesGrid){
    console.error("ساختار index.html ناقص است.");
    return;
  }

  const esc=v=>{const d=document.createElement("div");d.textContent=String(v);return d.innerHTML;};

  function openRecipe(id){
    const r=recipes[id];
    if(!r){alert("دستور پخت پیدا نشد.");return;}
    const ingredients=r.ingredients.map(x=>`<li>${esc(x)}</li>`).join("");
    const steps=r.steps.map((x,i)=>`<div class="cooking-step"><span class="step-number">${i+1}</span><p>${esc(x)}</p></div>`).join("");

    modalContent.innerHTML=`
      <div class="modal-recipe-header">
        <div class="modal-recipe-emoji">${r.emoji}</div>
        <span class="modal-recipe-category">${esc(r.category)}</span>
        <h2>${esc(r.name)}</h2>
        <p>مواد لازم و روش تهیه مخصوص ${esc(r.name)}</p>
      </div>
      <section class="recipe-detail-section">
        <h3>🛒 مواد لازم</h3>
        <ul class="ingredients-list">${ingredients}</ul>
      </section>
      <section class="recipe-detail-section">
        <h3>👩‍🍳 مراحل پخت</h3>
        <div class="cooking-steps">${steps}</div>
      </section>`;
    modal.classList.add("active");
    document.body.classList.add("recipe-modal-open");
  }

  function closeRecipe(){
    modal.classList.remove("active");
    document.body.classList.remove("recipe-modal-open");
  }

  recipesGrid.addEventListener("click",e=>{
    const b=e.target.closest(".view-recipe-btn");
    if(b) openRecipe(b.dataset.recipe);
  });
  closeButton.addEventListener("click",closeRecipe);
  backdrop.addEventListener("click",closeRecipe);
  document.addEventListener("keydown",e=>{if(e.key==="Escape")closeRecipe();});

  searchInput.addEventListener("input",()=>{
    const q=searchInput.value.trim().toLowerCase();
    document.querySelectorAll(".recipe-card").forEach(card=>{
      const name=(card.dataset.name||card.querySelector("h2")?.textContent||"").toLowerCase();
      card.hidden=q!==""&&!name.includes(q);
    });
  });
});
