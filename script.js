// ============================================
// ساخت لیست مواد لازم
// ============================================

function createIngredientsList(ingredients) {

    const list = document.createElement("ul");

    ingredients.forEach(function (ingredient) {

        const item = document.createElement("li");

        item.textContent = ingredient;

        list.appendChild(item);

    });

    return list;

}


// ============================================
// ساخت لیست مراحل پخت
// ============================================

function createStepsList(steps) {

    const list = document.createElement("ol");

    steps.forEach(function (step) {

        const item = document.createElement("li");

        item.textContent = step;

        list.appendChild(item);

    });

    return list;

}


// ============================================
// نمایش دستور پخت
// ============================================

function showRecipe(recipeId) {

    const recipe = recipes[recipeId];


    if (!recipe) {

        alert("دستور پخت این غذا هنوز به JavaScript اضافه نشده است.");

        console.error(
            "دستور غذا پیدا نشد:",
            recipeId
        );

        return;

    }


    modalRecipeContent.innerHTML = "";


    const recipeContainer = document.createElement("div");

    recipeContainer.className = "modal-recipe";


    const emoji = document.createElement("div");

    emoji.className = "modal-emoji";

    emoji.textContent = recipe.emoji;


    const title = document.createElement("h2");

    title.textContent = recipe.name;


    const time = document.createElement("p");

    time.textContent = "⏱ زمان پخت: " + recipe.time;


    const difficulty = document.createElement("p");

    difficulty.textContent =
        "📊 درجه سختی: " + recipe.difficulty;


    const ingredientsTitle = document.createElement("h3");

    ingredientsTitle.textContent = "🛒 مواد لازم";


    const ingredientsList =
        createIngredientsList(recipe.ingredients);


    const stepsTitle = document.createElement("h3");

    stepsTitle.textContent = "👩‍🍳 مراحل پخت";


    const stepsList =
        createStepsList(recipe.steps);


    recipeContainer.appendChild(emoji);

    recipeContainer.appendChild(title);

    recipeContainer.appendChild(time);

    recipeContainer.appendChild(difficulty);

    recipeContainer.appendChild(ingredientsTitle);

    recipeContainer.appendChild(ingredientsList);

    recipeContainer.appendChild(stepsTitle);

    recipeContainer.appendChild(stepsList);


    modalRecipeContent.appendChild(recipeContainer);


    recipeModal.classList.add("show");

}


